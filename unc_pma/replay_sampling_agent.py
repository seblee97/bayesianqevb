    def _sr_policy_probs(self, state: int, temp: float) -> np.ndarray:
        """Action-probability row for `state` under `self.SR_policy`.

        Feeds the on-policy transition matrix that the successor
        representation is built from — see `_successor_representation`.
        """
        q_means = self.q_model.q_means(state)
        if self.SR_policy == "thomson_sampling":
            return self.q_model.thomsom_sampling_probs(state)
        elif self.SR_policy == "q_means":
            return softmax_weights(q_means, temp=temp)
        elif self.SR_policy == "greedy":
            probs = np.zeros(self.q_model.n_actions)
            probs[np.argmax(q_means)] = 1.0
            return probs
        raise ValueError(f"Unknown SR_policy {self.SR_policy!r}")

    def _successor_representation(self, temp: float) -> tuple[np.ndarray, np.ndarray]:
        """Build SR(s, s') and the on-policy stationary distribution, once
        for the whole `sample_replay` bout.

        Neither q_model nor transition_model is updated while sampling
        simulated replay, so a single successor representation and
        stationary distribution (both under `self.SR_policy`) are valid
        for every EVB query made during the bout — no need to rebuild
        them per state-action pair.

        Mattar & Daw (2018) Online Methods, "Need term": Need(sk) is the
        nth row of SR = (I - gamma*T_pi)^-1 when the agent's current
        state n is known, or the stationary distribution mu (mu @ T_pi =
        mu) when it isn't (e.g. during sleep, used here for
        need_from_position=False). The stationary distribution isn't
        recoverable from SR alone, so T_pi is duplicated here from
        DirichletTransitionsModel.successor_representation.

        With a terminal_model, occupancy stops at terminal states:
        SR = (I - gamma * diag(c) T_pi)^-1, c = P(continue | s). With
        need_across_episodes, entering a terminal state is instead
        followed by a reset to `reset_state`, in both the SR and the
        stationary distribution.
        """
        policy_probs = np.array([
            self._sr_policy_probs(s, temp) for s in range(self.q_model.n_states)
        ])
        gamma = self.q_model.gamma
        mean_t = self.transition_model.alpha / self.transition_model.alpha.sum(axis=-1, keepdims=True)
        t_pi = np.einsum("sa,sap->sp", policy_probs, mean_t)

        # The stationary distribution (10k Cesaro iterations) is only
        # needed when Need isn't anchored at the agent's position.
        need_stationary = not self.need_from_position
        if self.terminal_model is None:
            sr = self.transition_model.successor_representation(gamma, policy_probs)
            return sr, self._stationary_distribution(t_pi) if need_stationary else None

        cont = self.terminal_model.continue_mean()
        chain = cont[:, None] * t_pi
        if self.need_across_episodes:
            reset = np.zeros(self.q_model.n_states)
            if np.ndim(self.reset_state) == 0:
                reset[int(self.reset_state)] = 1.0
            else:
                reset = np.asarray(self.reset_state, dtype=float) / np.sum(self.reset_state)
            chain += (1.0 - cont)[:, None] * reset[None, :]
            stationary_dist = self._stationary_distribution(chain) if need_stationary else None
        else:
            stationary_dist = self._stationary_distribution(t_pi) if need_stationary else None
        sr = np.linalg.inv(np.eye(self.q_model.n_states) - gamma * chain)
        return sr, stationary_dist

    @staticmethod
    def _stationary_distribution(t_pi: np.ndarray, n_iter: int = 10_000) -> np.ndarray:
        """Cesaro-averaged occupancy of t_pi from a uniform start:
        mu = mean over k=0..n_iter-1 of (uniform @ t_pi^k).

        Solving "mu @ t_pi = mu" directly needs t_pi irreducible, which
        fails once transitions are exact one-hot: under a deterministic
        policy (e.g. SR_policy="greedy") t_pi is a functional graph that
        generically splits into disjoint cycles (singular system) and/or
        is periodic (power iteration oscillates). Cesaro-averaging is
        always well-defined and converges regardless, and its "occupancy
        averaged over every starting state" reading is what
        need_from_position=False wants anyway.
        """
        n = t_pi.shape[0]
        mu = np.full(n, 1.0 / n)
        mu_sum = np.zeros(n)
        for _ in range(n_iter):
            mu_sum += mu
            mu = mu @ t_pi
        return mu_sum / n_iter

    def compute_all_evb(
        self,
        q_model: BayesianQLearning,
        sr: np.ndarray,
        stationary_dist: np.ndarray,
    ) -> np.ndarray:
        """EVB(s, a) for every state-action pair, reusing the precomputed `sr`/`stationary_dist`.

        Invalid states/pairs are forced to INVALID_EVB *after* the fact,
        overwriting whatever VPI x Need they happened to produce.
        """
        evb = np.empty((q_model.n_states, q_model.n_actions))
        for s in range(q_model.n_states):
            means = q_model.q_means(s)  # computed once per state, not once per (state, action)
            for a in range(q_model.n_actions):
                evb[s, a] = self.compute_single_evb(q_model, s, a, sr, stationary_dist, means=means)
        if self.valid_states is not None:
            evb[~self.valid_states, :] = INVALID_EVB
        if self.valid_state_actions is not None:
            evb[~self.valid_state_actions] = INVALID_EVB
        return evb

    def compute_single_evb(
        self,
        q_model: BayesianQLearning,
        s: int,
        a: int,
        sr: np.ndarray,
        stationary_dist: np.ndarray,
        means: np.ndarray | None = None,
    ) -> float:
        """EVB(s, a) = VPI(s, a) * Need(s, a).

        VPI comes straight from the Q-posterior. Need follows Mattar & Daw
        (2018): SR(agent_real_state, s) — the nth row of the SR matrix,
        where n is the agent's real current state — if `need_from_position`,
        else the on-policy stationary distribution at s (their "sleep"
        alternative, used when no single current position anchors Need).

        `means` (q_model.q_means(s)) can be passed in by a caller looping
        over every action at the same state, so it isn't rebuilt on every
        call — see compute_all_evb.
        """
        vpi = q_model.vpi(s, a, means=means)
        if self.need_from_position:
            need = float(sr[self.agent_real_state, s])
        else:
            need = float(stationary_dist[s])
        return vpi * need

